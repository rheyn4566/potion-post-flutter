"""Package the selected Imagegen outputs without repainting or distorting them."""
from pathlib import Path
import argparse
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = [
    ('daily', 'exec-6c59f210-b693-42a1-9322-99d520821838.png', 'assets/scenes/daily-office-v3.webp', None),
    ('workbench', 'exec-db557637-9b60-4ba7-b2da-742fe0fc6591.png', 'assets/scenes/potion-workbench-v3.webp', None),
    ('route', 'exec-7110e7e7-7a51-450d-b5f8-b5e2191c24b6.png', 'assets/scenes/woodland-route-v3.webp', None),
    ('ornament', 'exec-6a5c7e04-2d1d-4296-a6d2-7a1c5a283370.png', 'assets/ui/bloom-ornament-v3.webp', 256),
    ('plinth', 'exec-12d32635-f576-48ad-b591-e91e9ee08098.png', 'assets/ui/companion-plinth-v3.webp', 1024),
]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('originals', type=Path)
    args = parser.parse_args()
    manifest = []
    for key, original, relative, maximum in ASSETS:
        with Image.open(args.originals / original) as source:
            image = source.convert('RGBA')
        crop = None
        if maximum:
            bounds = image.getchannel('A').point(lambda value: 255 if value > 8 else 0).getbbox()
            assert bounds
            crop = [max(0, bounds[0]-12), max(0, bounds[1]-12), min(image.width, bounds[2]+12), min(image.height, bounds[3]+12)]
            image = image.crop(crop)
            image.thumbnail((maximum, maximum), Image.Resampling.LANCZOS)
        else:
            image = image.convert('RGB')
        destination = ROOT / relative
        image.save(destination, 'WEBP', quality=94, method=6, lossless=key == 'ornament')
        manifest.append(dict(key=key, original=original, path=relative, width=image.width, height=image.height, alpha_margin_crop=crop, bytes=destination.stat().st_size))
    (ROOT / 'docs/POLISHED_ART_ASSETS.json').write_text(json.dumps(manifest, indent=2))
    definitions = ["// Selected project artwork; generated by package_polished_art.py.", 'class StoryArt {']
    definitions += [f"  static const {item['key']} = '{item['path']}';" for item in manifest]
    plinth = next(item for item in manifest if item['key'] == 'plinth')
    definitions += [f"  static const plinthAspect = {plinth['width']} / {plinth['height']};", '}']
    (ROOT / 'lib/ui/polished_art.dart').write_text('\n'.join(definitions) + '\n')
    print(json.dumps(manifest, indent=2))

if __name__ == '__main__':
    main()
