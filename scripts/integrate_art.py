def webp(source, target, size):
    image = Image.open(source).convert('RGBA')
    alpha = image.getchannel('A')
    box = alpha.point(lambda a: 255 if a > 4 else 0).getbbox()
    if not box:
        raise ValueError(f'Empty artwork: {source}')
    image = image.crop(box)
    image.thumbnail((int(size[0] * .96), int(size[1] * .96)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', size)
    canvas.alpha_composite(image, ((size[0] - image.width) // 2, (size[1] - image.height) // 2))
    target.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(target, 'WEBP', quality=93, method=6, exact=True)
    return {'path': str(target.relative_to(ROOT)), 'bytes': target.stat().st_size}

def main():
    packaged = {}
    for source in sorted((ROOT / 'assets/characters').glob('*.png')):
        packaged[source.stem] = webp(source, source.with_suffix('.webp'), (576, 720))
    for kind, filename in CHARACTERS.items():
        source = ART / filename
        if kind == 'sloth':
            cleaned = WORKSPACE / 'generated_images/exec-7a5035c4-cf46-4dd3-9597-95f3191109cb.png'
            if cleaned.exists():
                source = cleaned
        packaged[kind] = webp(source, ROOT / f'assets/characters/{kind}.webp', (576, 720))
    garden_paths = {}
    for garden, filename in GARDENS.items():
        target = ROOT / f'assets/gardens/{garden}-scene.webp'
        webp(ART / filename, target, (960, 768))
        garden_paths[garden] = str(target.relative_to(ROOT))
    atlas = Image.open(ART / 'Transparent cozy game UI atlas.png').convert('RGBA')
    sprite_sizes = {}
    for name, box in SPRITES.items():
        sprite = atlas.crop(box)
        alpha = sprite.getchannel('A')
        bounds = alpha.point(lambda a: 255 if a > 5 else 0).getbbox()
        if not bounds:
            raise ValueError(f'Empty atlas region: {name}')
        sprite = sprite.crop(bounds)
        target = ROOT / f'assets/ui/{name}.webp'
        target.parent.mkdir(parents=True, exist_ok=True)
        sprite.save(target, 'WEBP', quality=96, method=6, exact=True)
        sprite_sizes[name] = list(sprite.size)
    dart = "// Generated by scripts/integrate_art.py from the approved artwork.\nimport 'package:flutter/widgets.dart';\n\n"
    dart += 'const gardenSceneAssets = <String, String>{\n'
    dart += ''.join(f"  '{key}': '{value}',\n" for key, value in garden_paths.items()) + '};\n\n'
    dart += 'const uiSpriteSizes = <String, Size>{\n'
    dart += ''.join(f"  '{key}': Size({value[0]}, {value[1]}),\n" for key, value in sprite_sizes.items()) + '};\n'
    (ROOT / 'lib/ui/scene_catalog.dart').write_text(dart)
    manifest = {'characters': packaged, 'gardenScenes': garden_paths, 'uiSprites': sprite_sizes,
                'processing': 'Existing alpha preserved; sprite extraction and WebP packaging only.',
                'slothEdit': 'Built-in Imagegen background-extraction; physical character preserved.'}
    (ROOT / 'docs/ART_ASSETS.json').write_text(json.dumps(manifest, indent=2))
    print(json.dumps({'characters': len(packaged), 'newGardenScenes': len(garden_paths), 'uiSprites': sprite_sizes}))

if __name__ == '__main__':
    main()
