"""Export selected generated worlds and normalize character alpha margins.

This only encodes and trims transparent padding. Illustration edits belong to
the built-in image generator; existing IDs and portrait assets are preserved.
"""
from pathlib import Path
import argparse
import json

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ALIASES = {
    'lavender': 'moonbloom', 'clovermeadow': 'sunpetal', 'owlwood': 'moonbloom',
    'bramblebrook': 'lilypond', 'otterbend': 'lilypond', 'hazelhedge': 'amberorchard',
    'cherryveil': 'sunpetal', 'mushroomvale': 'stargrove', 'buttercupbay': 'coralcove',
    'silverwillow': 'stargrove', 'rosegate': 'sunpetal', 'fireflyfen': 'lilypond',
    'peachterrace': 'amberorchard', 'crystalcreek': 'frostfern', 'fernwhisper': 'lilypond',
    'poppylantern': 'pumpkinpatch', 'wishinggarden': 'stargrove',
    'honeydewheights': 'cloudberry', 'cinnamonwood': 'amberorchard',
    'bluebellhollow': 'moonbloom', 'twilightorchid': 'stargrove',
    'auroraglen': 'frostfern', 'dandeliondrift': 'sunpetal', 'jadeisles': 'coralcove',
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('selected', type=Path)
    args = parser.parse_args()
    chosen = json.loads(args.selected.read_text())
    directory = ROOT / 'assets/worlds'
    directory.mkdir(exist_ok=True)
    manifest = []
    worlds = {a['id']: a for a in chosen if a['kind'] == 'world'}
    for identity, item in worlds.items():
        image = Image.open(item['original']).convert('RGBA')
        assert image.getchannel('A').getextrema() == (255, 255), identity
        image = image.convert('RGB')
        image.thumbnail((1536, 1536), Image.Resampling.LANCZOS)
        relative = f'assets/worlds/world-{identity}.webp'
        image.save(ROOT / relative, 'WEBP', quality=92, method=6)
        manifest.append({**item, 'path': relative, 'width': image.width,
                         'height': image.height, 'bytes': (ROOT / relative).stat().st_size})
    poses = {a['id']: a for a in chosen if a['kind'] == 'character'}
    for old in sorted((ROOT / 'assets/characters').glob('*.webp')):
        identity = old.stem
        item = poses.get(identity)
        original = Path(item['original']) if item else old
        image = Image.open(original).convert('RGBA')
        bounds = image.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
        assert bounds, identity
        image = image.crop(bounds)
        image.thumbnail((768, 768), Image.Resampling.LANCZOS)
        relative = f'assets/worlds/pose-{identity}.webp'
        image.save(ROOT / relative, 'WEBP', quality=94, alpha_quality=100,
                   exact=True, method=6)
        manifest.append({'id': identity, 'kind': 'character-pose',
                         'source': str(original), 'new_generated_pose': bool(item),
                         'path': relative, 'width': image.width, 'height': image.height,
                         'alpha_margin_crop': bounds,
                         'bytes': (ROOT / relative).stat().st_size,
                         **({'prompt': item['prompt'], 'tool': item['tool']} if item else {})})
    assert len(worlds) == 19
    assert len([m for m in manifest if m['kind'] == 'character-pose']) == 26
    (ROOT / 'docs/WORLD_ART_ASSETS.json').write_text(json.dumps(manifest, indent=2))
    definitions = ["// Generated by scripts/package_world_art.py.",
                   "import 'package:flutter/material.dart';", '', 'class WorldArt {',
                   '  static const worlds = <String>{']
    definitions += [f"    '{identity}'," for identity in worlds]
    definitions += ['  };', '  static const aliases = <String, String>{']
    definitions += [f"    '{identity}': '{target}'," for identity, target in ALIASES.items()]
    definitions += [
        '  };',
        "  static String worldId(String garden) => worlds.contains(garden) ? garden : (aliases[garden] ?? 'moonbloom');",
        "  static String environment(String garden) => 'assets/worlds/world-${worldId(garden)}.webp';",
        "  static String pose(String kind) => 'assets/worlds/pose-$kind.webp';",
        '  static Color groundColor(String garden) => switch (worldId(garden)) {',
        "    'frostfern' => const Color(0xFFB8C5BE),",
        "    'cactuscrescent' || 'coralcove' => const Color(0xFF99915A),",
        "    'amberorchard' || 'copperwind' => const Color(0xFF847543),",
        '    _ => const Color(0xFF587C39),', '  };', '}',
    ]
    (ROOT / 'lib/ui/world_art.dart').write_text('\n'.join(definitions) + '\n')
    print(f'Exported {len(worlds)} opaque worlds and 26 grounded pose assets; 3 new poses.')


if __name__ == '__main__':
    main()
